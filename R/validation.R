#================== Scalar Arguments ==================

#Validate and return one integer at or above the requested minimum.
.validate_count <- function(x, name, minimum = 1L) {
  if (
    !is.numeric(x) ||
    is.logical(x) ||
    length(x) != 1L ||
    is.na(x) ||
    !is.finite(x) ||
    x != floor(x) ||
    x < minimum
  ) {
    stop(
      '"', name, '" must be a single integer greater than or equal to ',
      minimum, ".",
      call. = FALSE
    )
  }

  as.integer(x)
}


#Validate and return one non-empty character value.
.validate_name <- function(x, name = "name") {
  if (
    !is.character(x) ||
    length(x) != 1L ||
    is.na(x) ||
    !nzchar(trimws(x))
  ) {
    stop(
      '"', name, '" must be a single non-empty character value.',
      call. = FALSE
    )
  }

  trimws(x)
}


#Validate and return one logical flag.
.validate_flag <- function(x, name) {
  if (!is.logical(x) || length(x) != 1L || is.na(x)) {
    stop('"', name, '" must be TRUE or FALSE.', call. = FALSE)
  }

  x
}


#Validate a base-graphics axis-label orientation. These are the four values
#accepted by graphics::par("las") and graphics::axis().
.validate_las <- function(x, name = "las") {
  if (
    !is.numeric(x) ||
    is.logical(x) ||
    length(x) != 1L ||
    is.na(x) ||
    !x %in% 0:3
  ) {
    stop('"', name, '" must be one of 0, 1, 2, or 3.', call. = FALSE)
  }

  as.integer(x)
}


#Protect named stored results from accidental replacement while allowing a
#caller to request replacement explicitly. The new result should be assigned
#only after its calculation has completed successfully.
.validate_overwrite_name <- function(
    name,
    existing,
    overwrite,
    what = "object"
) {
  overwrite <- .validate_flag(overwrite, "overwrite")

  if (name %in% existing && !overwrite) {
    stop(
      'A stored ', what, ' named "', name,
      '" already exists. Set "overwrite = TRUE" to replace it.',
      call. = FALSE
    )
  }

  overwrite
}


#Validate an optional random-number seed.
.validate_seed <- function(seed, name = "seed") {
  if (is.null(seed)) {
    return(NULL)
  }

  if (
    !is.numeric(seed) ||
    is.logical(seed) ||
    length(seed) != 1L ||
    is.na(seed) ||
    !is.finite(seed) ||
    seed != floor(seed) ||
    seed < 0 ||
    seed > .Machine$integer.max
  ) {
    stop(
      '"', name, '" must be NULL or a single non-negative integer.',
      call. = FALSE
    )
  }

  as.integer(seed)
}


#================== Names and Imported Data ==================

#Columns generated by the campaign, run-sheet, prediction, and surface APIs.
#Protecting them when factors are declared prevents ambiguous output tables.
.structural_column_names <- function() {
  c("Batch", "Type", "Run")
}


.prediction_column_names <- function() {
  c(
    "prediction",
    "response_mean",
    "prediction_lower",
    "prediction_upper",
    "model_mean",
    "model_sd"
  )
}


.reserved_factor_names <- function() {
  unique(c(
    .structural_column_names(),
    .prediction_column_names(),
    "latent_mean"
  ))
}

#Validate factor labels that will become campaign-data columns.
.validate_factor_names <- function(
    labels,
    reserved = .reserved_factor_names()
) {
  if (
    !is.character(labels) ||
    !length(labels) ||
    anyNA(labels) ||
    any(!nzchar(trimws(labels)))
  ) {
    stop(
      "Factor labels must be non-missing, non-empty character values.",
      call. = FALSE
    )
  }

  labels <- trimws(labels)

  if (anyDuplicated(tolower(labels))) {
    stop(
      "Factor labels must be unique, ignoring capitalization.",
      call. = FALSE
    )
  }

  reserved_match <- tolower(labels) %in% tolower(reserved)
  if (any(reserved_match)) {
    stop(
      "Reserved column name(s) cannot be used as factor labels: ",
      paste(labels[reserved_match], collapse = ", "),
      ".",
      call. = FALSE
    )
  }

  labels
}


#Validate the response name against factor and reserved campaign columns.
.validate_response_name <- function(
    response,
    factor_labels,
    reserved = .structural_column_names()
) {
  response <- .validate_name(response, "response")

  if (tolower(response) %in% tolower(c(factor_labels, reserved))) {
    stop(
      '"response" must not duplicate a factor label or reserved column name.',
      call. = FALSE
    )
  }

  response
}


#Convert selected imported columns to finite numeric values. This deliberate
#normalization is confined to data-frame input; scalar arguments remain strict.
.validate_numeric_columns <- function(data, columns, what = "data") {
  missing_columns <- setdiff(columns, names(data))
  if (length(missing_columns)) {
    stop(
      what, " is missing column(s): ",
      paste(missing_columns, collapse = ", "),
      ".",
      call. = FALSE
    )
  }

  for (column in columns) {
    value <- data[[column]]
    if (is.factor(value)) {
      value <- as.character(value)
    }
    value <- suppressWarnings(as.numeric(value))

    if (length(value) != nrow(data) || anyNA(value) || any(!is.finite(value))) {
      stop(
        what, ' contains non-numeric or non-finite values in "',
        column, '".',
        call. = FALSE
      )
    }

    data[[column]] <- value
  }

  data
}


#Check physical values before applying declared log10 transformations.
.validate_log_domain <- function(data, design, what = "Factor values") {
  log_factors <- design@label[design@transform == "log10"]
  if (!length(log_factors)) {
    return(invisible(TRUE))
  }

  non_positive <- vapply(
    log_factors,
    function(label) any(data[[label]] <= 0),
    logical(1)
  )

  if (any(non_positive)) {
    stop(
      what,
      " must be strictly positive for log10-transformed factor(s): ",
      paste(log_factors[non_positive], collapse = ", "),
      ".",
      call. = FALSE
    )
  }

  invisible(TRUE)
}


#Validate the replicate count for one fixed reference condition.
.validate_replicates <- function(replicates, n_controls) {
  if (
    n_controls != 1L ||
    !is.numeric(replicates) ||
    is.logical(replicates) ||
    length(replicates) != 1L ||
    is.na(replicates) ||
    !is.finite(replicates) ||
    replicates != floor(replicates) ||
    replicates < 1L
  ) {
    stop(
      'A campaign with references requires one fixed reference condition ',
      'and one positive integer supplied through "replicates".',
      call. = FALSE
    )
  }

  as.integer(replicates)
}


#Validate a normalized response column against the declared transformation.
.validate_response_values <- function(values, transform, what = "The response") {
  if (!is.numeric(values) || anyNA(values) || any(!is.finite(values))) {
    stop(what, " must contain only finite numeric values.", call. = FALSE)
  }

  if (identical(transform, "log") && any(values <= 0)) {
    stop(what, " must be strictly positive when log-transformed.", call. = FALSE)
  }

  invisible(TRUE)
}


#================== Optimization Controls ==================

#Validate paired numeric bounds and return their normalized values.
.validate_bounds <- function(
    lower,
    upper,
    length_required,
    name = "bounds",
    positive = FALSE
) {
  if (
    !is.numeric(lower) ||
    is.logical(lower) ||
    !is.numeric(upper) ||
    is.logical(upper) ||
    length(lower) != length_required ||
    length(upper) != length_required ||
    anyNA(c(lower, upper)) ||
    any(!is.finite(c(lower, upper)))
  ) {
    stop(
      'The lower and upper "', name, '" must each contain ',
      length_required, " finite numeric values.",
      call. = FALSE
    )
  }

  if (positive && any(c(lower, upper) <= 0)) {
    stop('The "', name, '" must be strictly positive.', call. = FALSE)
  }

  if (any(lower >= upper)) {
    stop(
      'Every lower "', name,
      '" must be strictly below its corresponding upper bound.',
      call. = FALSE
    )
  }

  list(lower = as.numeric(lower), upper = as.numeric(upper))
}


#Validate user-configurable controls consumed by gp_fit_mlii().
.validate_mlii_controls <- function(
    n_starts,
    maxit,
    jitter,
    lower,
    upper
) {
  n_starts <- .validate_count(n_starts, "n_starts")
  maxit <- .validate_count(maxit, "maxit")

  if (
    !is.numeric(jitter) ||
    is.logical(jitter) ||
    length(jitter) != 1L ||
    is.na(jitter) ||
    !is.finite(jitter) ||
    jitter < 0
  ) {
    stop(
      '"jitter" must be a single finite non-negative numeric value.',
      call. = FALSE
    )
  }

  bounds <- .validate_bounds(
    lower = lower,
    upper = upper,
    length_required = 4L,
    name = "ML-II bounds",
    positive = TRUE
  )

  list(
    n_starts = n_starts,
    maxit = maxit,
    jitter = as.numeric(jitter),
    lower = bounds$lower,
    upper = bounds$upper
  )
}


#Validate the controls shared by the internal greedy acquisition optimizer.
.validate_acquisition_controls <- function(
    n_screen,
    restarts,
    maxit,
    lower,
    upper,
    D,
    max_screen_factor = 4L,
    seed = NULL
) {
  n_screen <- .validate_count(n_screen, "n_screen")
  restarts <- .validate_count(restarts, "restarts")
  maxit <- .validate_count(maxit, "maxit")
  max_screen_factor <- .validate_count(
    max_screen_factor,
    "max_screen_factor"
  )
  seed <- .validate_seed(seed)

  if (restarts > n_screen) {
    stop(
      '"restarts" cannot exceed the initial Sobol screen size "n_screen".',
      call. = FALSE
    )
  }

  if (is.null(lower)) lower <- rep(0, D)
  if (is.null(upper)) upper <- rep(1, D)

  bounds <- .validate_bounds(
    lower = lower,
    upper = upper,
    length_required = D,
    name = "acquisition bounds"
  )

  list(
    n_screen = n_screen,
    restarts = restarts,
    maxit = maxit,
    lower = bounds$lower,
    upper = bounds$upper,
    max_screen_factor = max_screen_factor,
    seed = seed
  )
}


#================== Numerical Output Contracts ==================

#Require one finite acquisition value for every candidate row.
.validate_screen_values <- function(values, n_candidates) {
  if (
    !is.numeric(values) ||
    is.logical(values) ||
    length(values) != n_candidates ||
    anyNA(values) ||
    any(!is.finite(values))
  ) {
    stop(
      "The acquisition function must return one finite numeric value per candidate.",
      call. = FALSE
    )
  }

  as.numeric(values)
}


#Require the scalar finite value expected by optim() for one candidate.
.validate_objective_value <- function(value) {
  if (
    !is.numeric(value) ||
    is.logical(value) ||
    length(value) != 1L ||
    is.na(value) ||
    !is.finite(value)
  ) {
    stop(
      "The acquisition objective must return one finite numeric value for a candidate.",
      call. = FALSE
    )
  }

  as.numeric(value)
}


#Validate the final internal acquisition result before it is decoded and stored.
.validate_proposal_matrix <- function(X, q, D) {
  X <- as.matrix(X)

  if (
    !is.numeric(X) ||
    nrow(X) != q ||
    ncol(X) != D ||
    anyNA(X) ||
    any(!is.finite(X))
  ) {
    stop("The acquisition function returned an invalid proposal matrix.", call. = FALSE)
  }

  if (any(X < -1e-8 | X > 1 + 1e-8)) {
    stop(
      "The acquisition function returned a condition outside [0, 1].",
      call. = FALSE
    )
  }

  #L-BFGS-B may return a boundary value a few floating-point units outside its
  #box. Values within the accepted numerical tolerance represent the boundary
  #itself and must be snapped back before conversion to physical units.
  X[X < 0] <- 0
  X[X > 1] <- 1

  X
}


#Return a useful optimizer message even when optim() supplies none.
.optimizer_message <- function(convergence, message = NULL) {
  if (length(convergence) == 1L && !is.na(convergence) && convergence == 0L) {
    return("Converged")
  }

  if (length(message) == 1L && !is.na(message) && nzchar(message)) {
    return(as.character(message))
  }

  if (length(convergence) == 1L && !is.na(convergence)) {
    return(paste0("Optimization ended with convergence code ", convergence, "."))
  }

  "Optimization did not return a convergence code."
}
